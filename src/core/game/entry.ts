import type { Game } from "./game";

// Формат записи игры — реестра. Это единственное, что платформа знает об игре
// до её запуска: конкретных игр ядро не знает, оно умеет только получать список
// записей (см. registry.ts).

/**
 * Запись об игре. Идентификатор и название задаются внутри игры и не зависят от
 * имени папки, поэтому переименование папки ничего не ломает.
 */
export interface GameEntry {
  /** Уникальный идентификатор, стабильный между запусками. */
  readonly id: string;
  /** Название для интерфейса. */
  readonly label: string;
  /**
   * Точка входа: отложенная загрузка игры. Возвращает готовый экземпляр.
   * Отложенность нужна, чтобы игры грузились по требованию, а не все сразу.
   */
  readonly entry: () => Promise<Game>;
}
