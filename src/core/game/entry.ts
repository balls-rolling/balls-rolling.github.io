// Формат записи игры — реестра. Контракт поведения (жизненный цикл, сессия,
// демо) — это фаза 02; здесь фиксируется только формат, чтобы он существовал
// до того, как появится первая игра.

/** Точка входа плагина окружения. Платформа забирает плагины перед запуском. */
export type PluginEntry = () => unknown;

/**
 * Запись об игре: всё, что платформа знает об игре до её запуска.
 * Идентификатор и название задаются внутри игры и не зависят от имени папки,
 * поэтому переименование папки ничего не ломает.
 */
export interface GameEntry {
  /** Уникальный идентификатор, стабильный между запусками. */
  readonly id: string;
  /** Название для интерфейса. */
  readonly label: string;
  /** Точка входа игры: модуль с её описанием и классом. */
  readonly entry: () => Promise<unknown>;
  /** Плагины, которые игра добавляет в интерфейс игрового окружения. */
  readonly plugins?: readonly PluginEntry[];
  /** Точка входа демо: запускает демонстрацию для этой игры. */
  readonly demo?: () => Promise<unknown>;
}
