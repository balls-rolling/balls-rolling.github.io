// Хранилище ключ-значение. Все методы асинхронные с самого начала: localStorage
// синхронный, IndexedDB — нет, и общий знаменатель только Promise. Благодаря
// этому переход на IndexedDB позже не изменит вызывающий код.

/**
 * Схема значения: значения по умолчанию и разбор произвольных данных.
 * Хранилище схем не знает — она передаётся на каждый вызов, поэтому платформа
 * и каждая игра объявляют свои свойства сами.
 *
 * `parse` не должен бросать: если данные испорчены, он обязан вернуть
 * пригодное значение, а не уронить чтение.
 */
export interface Schema<T> {
  readonly defaults: T;
  parse(raw: unknown): T;
}

export interface KeyValueStore {
  /** Всегда возвращает значение: при отсутствии или порче данных — defaults. */
  read<T>(key: string, schema: Schema<T>): Promise<T>;
  /** Запись не гарантирует персистентность: при переполнении она тихо не срабатывает. */
  write<T>(key: string, value: T): Promise<void>;
  remove(key: string): Promise<void>;
}
